#!/usr/bin/env bash
set -euo pipefail

DART_TEST_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
DART_TEST_TMP="$(mktemp -d /tmp/dart-serial-crc.XXXXXX)"
trap 'rm -rf -- "$DART_TEST_TMP"' EXIT

mkdir "$DART_TEST_TMP/work"
ln -s "$DART_TEST_ROOT/config" "$DART_TEST_TMP/config"

pkg-config --exists opencv4
read -r -a DART_TEST_OPENCV_CFLAGS <<< "$(pkg-config --cflags opencv4)"
DART_TEST_DEPENDENCY_FLAGS=()
for DART_TEST_FLAG in "${DART_TEST_OPENCV_CFLAGS[@]}"; do
    if [[ "$DART_TEST_FLAG" == -I* ]]; then
        DART_TEST_DEPENDENCY_FLAGS+=(-isystem "${DART_TEST_FLAG#-I}")
    else
        DART_TEST_DEPENDENCY_FLAGS+=("$DART_TEST_FLAG")
    fi
done
DART_TEST_CXX="${CXX:-g++}"

"$DART_TEST_CXX" -std=gnu++20 -O1 -g \
    -fsanitize=undefined,bounds -fno-sanitize-recover=all \
    -fno-omit-frame-pointer \
    "${DART_TEST_DEPENDENCY_FLAGS[@]}" \
    -I"$DART_TEST_ROOT/src/sensors/inc" \
    -I"$DART_TEST_ROOT/src/utility/inc" \
    -I"$DART_TEST_ROOT/config/autogenerated_flatbuffers" \
    -I"$DART_TEST_ROOT/.deps/flatbuffers-25.2.10/include" \
    "$DART_TEST_ROOT/tests/serial_crc_regression.cpp" \
    "$DART_TEST_ROOT/src/sensors/src/serialport/SerialPort.cpp" \
    "$DART_TEST_ROOT/src/sensors/src/serialport/CRC_Check.cpp" \
    "$DART_TEST_ROOT/src/utility/src/json/ReJson.cpp" \
    -Wl,--wrap=open -lopencv_core -o "$DART_TEST_TMP/serial_crc_regression"

cd "$DART_TEST_TMP/work"
UBSAN_OPTIONS=halt_on_error=1:print_stacktrace=1 "$DART_TEST_TMP/serial_crc_regression"
